export function resolveCodeThemePalette(
  themeName: LightCodeTheme | DarkCodeTheme,
): CodeThemePalette {
  if (themeName in LIGHT_CODE_THEME_PALETTES) {
    return LIGHT_CODE_THEME_PALETTES[themeName as LightCodeTheme];
  }
  return DARK_CODE_THEME_PALETTES[themeName as DarkCodeTheme];
}
