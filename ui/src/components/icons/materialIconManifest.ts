export interface ResolveMaterialIconOptions {
  readonly isFolder?: boolean;
  readonly isOpen?: boolean;
  readonly themeVariant?: "default" | "light" | "gruvbox_dark" | "gruvbox_light";
}

/**
 * Deterministic basename-first, extension-second, theme-aware Material SVG icon resolver.
 */
export function resolveMaterialIconId(
  filePathOrName: string,
  options: ResolveMaterialIconOptions = {},
): MaterialIconId {
  const normalized = filePathOrName.replace(/\\/g, "/").trim();
  const segments = normalized.split("/").filter(Boolean);
  const basename = (segments[segments.length - 1] ?? normalized).toLowerCase();

  let baseIcon: MaterialIconId = "document";

  if (options.isFolder) {
    const mappedFolder = FOLDER_ICON_MAP[basename];
    if (mappedFolder) {
      if (options.isOpen) {
        const openCandidate = `${mappedFolder}-open`;
        if (isMaterialIconId(openCandidate)) {
          return openCandidate;
        }
      }
      return mappedFolder;
    }
    return options.isOpen && isMaterialIconId("folder-base-open")
      ? "folder-base-open"
      : isMaterialIconId("folder-base")
        ? "folder-base"
        : "folder";
  }

  // 1. Exact basename match
  const byBasename = BASENAME_ICON_MAP[basename];
  if (byBasename && isMaterialIconId(byBasename)) {
    baseIcon = byBasename;
  } else if (basename.endsWith(".d.ts") && isMaterialIconId("typescript-def")) {
    baseIcon = "typescript-def";
  } else if (basename.endsWith("_test.go") || basename.endsWith(".test.go")) {
    baseIcon = isMaterialIconId("go") ? "go" : "document";
  } else {
    // 2. Extension match
    const dotIndex = basename.lastIndexOf(".");
    if (dotIndex > 0 && dotIndex < basename.length - 1) {
      const ext = basename.slice(dotIndex + 1);
      const byExt = EXTENSION_ICON_MAP[ext];
      if (byExt && isMaterialIconId(byExt)) {
        baseIcon = byExt;
      } else if (isMaterialIconId(ext)) {
        baseIcon = ext;
      }
    }
  }

  // 3. Apply optional theme variant suffix (_light, _gruvbox_dark, _gruvbox_light) if available
  if (options.themeVariant && options.themeVariant !== "default") {
    const variantCandidate = `${baseIcon}_${options.themeVariant}`;
    if (isMaterialIconId(variantCandidate)) {
      return variantCandidate;
    }
  }

  return baseIcon;
}

export function getMaterialIconAssetPath(iconId: MaterialIconId): string {
  return `/src/assets/material-icons/${iconId}.svg`;
}
